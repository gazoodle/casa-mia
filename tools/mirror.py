#!/usr/bin/env python3
"""Publish each component that is also offered by itself to a repository of its own.

HACS and Home Assistant's Marketplace take one item per repository, so a component named in
`casa_mia.components.PUBLISHED` gets a mirror: a generated repository holding the component
as it was released, a README from its guide, `hacs.json`, the licence and a workflow that
validates it. Nothing in a mirror is edited by hand (docs/design/marketplace-mirrors.md).

    tools/mirror.py --dry-run [ref]   generate from ref (HEAD) and check it; publishes nothing
    tools/mirror.py [version]         publish the mirrors of a release (this checkout's)

`tools/release.py` runs it as its last step; run alone, it retries. For each component whose
version is the release's, after your OK:

  1. Wait for Casa Mia's Release workflow to succeed, so that a mirror never gets ahead of
     an app that failed to build.
  2. Generate the mirror's tree from the release's tag, and check it here.
  3. Create the mirror if it is missing, then commit and push.
  4. Wait for the mirror's own validation; only then tag it and publish its release, with
     the component as a ZIP (`hacs.json`'s `filename`), which HACS and the Marketplace
     download. A release of the mirror still without its ZIP is given one too.

Run again after a failure, it carries on: a mirror already tagged with the same files is
done, and one tagged with different files stops and says so. A fork publishes no mirror
unless CM_MIRROR_OWNER names the account to put it in.

Needs the venv, git and the GitHub CLI logged in. hassfest runs here when docker does.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import posixpath
import re
import shutil
import subprocess
import sys
import tempfile
import time
import zipfile
from pathlib import Path

from casa_mia.components import PUBLISHED

sys.path.insert(0, str(Path(__file__).resolve().parent))
import versioning  # tools/, next to this script
from release import (
    ROOT,
    Stop,
    ask,
    git,
    github_repo,
    good,
    run,
    say,
    version_at,
    warn,
)

COMPONENTS = "integration/custom_components"
GUIDES = "docs/applets"
TOPICS = "home-assistant,hacs,custom-integration"
HASSFEST = "ghcr.io/home-assistant/hassfest"
PICTURES = (".webp", ".png", ".jpg", ".gif", ".svg")
# Every member's time in a release's ZIP, so the same files always give the same bytes.
ZIP_TIME = (1980, 1, 1, 0, 0, 0)
# What HACS's validation requires of a component's manifest.
MANIFEST_KEYS = (
    "codeowners",
    "documentation",
    "domain",
    "issue_tracker",
    "name",
    "version",
)
# A link's target: inline, a picture's src, or a reference's definition.
LINK = re.compile(r'(\]\(|src="|^\[[^\]]+\]: )([^)\s"]+)', re.M)

WORKFLOW = """\
# Generated by Casa Mia's tools/mirror.py: an edit here is lost at the next release.
name: Validate
on:
  push:
    branches: [main]
  workflow_dispatch:
permissions:
  contents: read
jobs:
  hacs:
    runs-on: ubuntu-latest
    steps:
      - uses: hacs/action@main
        with:
          category: integration
  hassfest:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v7
      - uses: home-assistant/actions/hassfest@master
"""

# Issues stay on in a mirror, because HACS's validation refuses a repository with them off.
# With no blank issues and no template, the only choice it offers is this link.
ISSUES = """\
blank_issues_enabled: false
contact_links:
  - name: Report a problem with {name}
    url: {tracker}
    about: {name} is part of Casa Mia, and its issues are kept there.
"""

README = """\

## Installing

[![Downloads](https://img.shields.io/github/downloads/{mirror}/total?label=Downloads)](https://github.com/{mirror}/releases)

The Downloads badge is GitHub's count of downloads of the releases' packages. Every
update and every repeat download adds to it, so it isn't the number of houses using
{name}.

{name} needs Home Assistant {minimum} or later.

1. In HACS, or in Home Assistant's Marketplace (2026.11 and later), add
   `https://github.com/{mirror}` as a custom repository of the type Integration.
2. Download {name} there, then restart Home Assistant.
3. In Settings → Devices & services, choose Add integration and pick {name}.

The [guide]({guide}) covers setting it up and everything on its page.

## Part of Casa Mia

{name} is part of [Casa Mia](https://github.com/{repo}), where it is written and
released. This repository is generated from Casa Mia {version} (commit `{commit}`) and
isn't edited by hand, so [issues]({tracker}) and changes go to Casa Mia.

The Casa Mia app installs this same integration itself. A house with both needs to do
nothing about it: [With HACS or the Marketplace]({guide}#with-hacs-or-the-marketplace)
says what happens.
"""


def guide_of(domain: str) -> str:
    return f"{GUIDES}/{PUBLISHED[domain].removeprefix('casa-mia-')}.md"


def manifest_at(domain: str, ref: str) -> dict:
    return json.loads(git("show", f"{ref}:{COMPONENTS}/{domain}/manifest.json"))


def mirror_owner(origin: str, issue_tracker: str, named: str | None) -> str | None:
    """Whose account a mirror goes in: the one named (CM_MIRROR_OWNER), else origin's owner
    when origin is the repository the component calls its own (its issue tracker's). None
    for a fork that names nobody: it has no mirror."""
    ours = issue_tracker.lower().startswith(f"https://github.com/{origin.lower()}/")
    return named or (origin.split("/")[0] if ours else None)


def mirror_url(origin_url: str, mirror: str) -> str:
    """The mirror's address, reached the way origin is (https or ssh)."""
    return re.sub(r"[^/:]+/[^/]+$", f"{mirror}.git", origin_url.rstrip("/"))


def decide(new: str, tagged: str, head: str) -> str:
    """What a run does to a mirror, from three tree ids: the one just generated, the one
    its tag for this version holds, and the one its main branch holds (empty when there is
    none). Comparing trees is what makes a retry safe: it carries on from wherever the last
    run stopped, and a published version is never changed."""
    if tagged:
        return "done" if tagged == new else "stop"
    return "tag" if head == new else "commit"


def absolute(text: str, guide: str, repo: str, ref: str) -> str:
    """A piece of the guide with each link and picture made to work from another
    repository: a path in Casa Mia becomes its address on GitHub at `ref`, and an anchor
    points into the whole guide, since the section it names may not have come along."""

    def swap(found: re.Match[str]) -> str:
        lead, target = found.groups()
        if re.match(r"[a-z]+:", target):
            return found.group(0)
        path, _, anchor = target.partition("#")
        # An anchor alone is a place in the guide itself.
        path = posixpath.normpath(posixpath.join(guide, "..", path)) if path else guide
        base = (
            f"https://raw.githubusercontent.com/{repo}/{ref}"
            if path.endswith(PICTURES)
            else f"https://github.com/{repo}/blob/{ref}"
        )
        return f"{lead}{base}/{path}{'#' + anchor if anchor else ''}"

    return LINK.sub(swap, text)


def opening(guide_text: str) -> str:
    """The guide down to its second section (what it is, and what it's for), with the
    definitions of the reference links used there."""
    heads = [found.start() for found in re.finditer(r"^## ", guide_text, re.M)]
    top = guide_text[: heads[1]] if len(heads) > 1 else guide_text
    used = set(re.findall(r"\]\[([^\]]+)\]", top))
    definitions = [
        line
        for line in guide_text.splitlines()
        if (found := re.match(r"\[([^\]]+)\]: ", line)) and found[1] in used
    ]
    return top.rstrip() + "\n" + "".join(f"\n{line}" for line in definitions) + "\n"


def zip_name(domain: str) -> str:
    """The release asset a store downloads: sensor_watch.zip for casa-mia-sensor-watch."""
    return PUBLISHED[domain].removeprefix("casa-mia-").replace("-", "_") + ".zip"


def component_at(domain: str, ref: str, into: Path) -> Path:
    """Writes the component exactly as committed at `ref`, compiled assets included, into
    `into`/<domain>, and returns that folder."""
    into.mkdir(parents=True, exist_ok=True)
    archive = subprocess.run(
        ["git", "archive", f"{ref}:{COMPONENTS}", domain],
        cwd=ROOT,
        capture_output=True,
    )
    if archive.returncode:
        raise Stop(f"{domain} at {ref}: {archive.stderr.decode().strip()}")
    subprocess.run(["tar", "-x", "-C", into], input=archive.stdout, check=True)
    return into / domain


def package(component: Path, archive: Path) -> Path:
    """The component as the ZIP a store unpacks into custom_components/<domain>: its files
    at the archive's root, with no folder around them (HACS 2.0.5
    `repositories/base.py` `async_download_zip_file`, and the Marketplace's, extract it
    there whole)."""
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as out:
        for path in sorted(p for p in component.rglob("*") if p.is_file()):
            member = zipfile.ZipInfo(path.relative_to(component).as_posix(), ZIP_TIME)
            member.compress_type = zipfile.ZIP_DEFLATED
            member.external_attr = 0o644 << 16
            out.writestr(member, path.read_bytes())
    return archive


def archive_problems(archive: Path, domain: str, ref: str) -> list[str]:
    """What is wrong with a release's ZIP, against the component as committed at `ref`
    (the files the Casa Mia app installs): each of them at the archive's root, byte for
    byte, and nothing else. Compared by git's own blob ids, so the check doesn't share
    the code that built the archive."""
    want = {}
    for line in git("ls-tree", "-r", f"{ref}:{COMPONENTS}/{domain}").splitlines():
        info, path = line.split("\t", 1)
        want[path] = info.split()[2]
    with zipfile.ZipFile(archive) as zipped:
        got = {
            member.filename: hashlib.sha1(
                b"blob %d\0" % member.file_size + zipped.read(member)
            ).hexdigest()
            for member in zipped.infolist()
            if not member.is_dir()
        }

    name = archive.name
    found = (
        [] if "manifest.json" in got else [f"{name} has no manifest.json at its root"]
    )
    found += [f"{name} lacks {path}" for path in sorted(want.keys() - got.keys())]
    found += [
        f"{name} holds {path}, not in {domain}"
        for path in sorted(got.keys() - want.keys())
    ]
    found += [
        f"{name}'s {path} differs from the committed one"
        for path in sorted(want.keys() & got.keys())
        if want[path] != got[path]
    ]
    return found


def build(domain: str, repo: str, ref: str, owner: str, out: Path) -> dict:
    """Writes `domain`'s mirror, as Casa Mia was at `ref`, into the empty folder `out`.
    Returns the component's manifest."""
    component = component_at(domain, ref, out / "custom_components")
    manifest = json.loads((component / "manifest.json").read_text("utf-8"))

    # Links name the release's tag when there is one, so they still work when main moves on.
    commit = git("rev-parse", f"{ref}^{{commit}}")
    at = ref if git("tag", "--list", ref) else commit
    guide = guide_of(domain)
    minimum = re.search(
        r'^homeassistant: "(.+)"', git("show", f"{ref}:app/config.yaml"), re.M
    )
    if not minimum:
        raise Stop(f"app/config.yaml at {ref} names no minimum Home Assistant.")
    words = {
        "name": manifest["name"],
        "tracker": manifest["issue_tracker"],
        "minimum": minimum[1],
        "mirror": f"{owner}/{PUBLISHED[domain]}",
        "guide": f"https://github.com/{repo}/blob/{at}/{guide}",
        "repo": repo,
        "version": version_at(ref),
        "commit": commit[:10],
    }

    files = {
        "README.md": absolute(opening(git("show", f"{ref}:{guide}")), guide, repo, at)
        + README.format(**words),
        # zip_release: a store downloads the release's ZIP rather than the repository's
        # files. That has no default branch to come from, so it isn't offered.
        "hacs.json": json.dumps(
            {
                "name": manifest["name"],
                "homeassistant": minimum[1],
                "zip_release": True,
                "filename": zip_name(domain),
                "hide_default_branch": True,
            },
            indent=2,
        )
        + "\n",
        "LICENSE": git("show", f"{ref}:LICENSE") + "\n",
        ".github/workflows/validate.yml": WORKFLOW,
        ".github/ISSUE_TEMPLATE/config.yml": ISSUES.format(**words),
    }
    for path, text in files.items():
        (out / path).parent.mkdir(parents=True, exist_ok=True)
        (out / path).write_text(text, encoding="utf-8")
    return manifest


def problems(out: Path, domain: str, repo: str, ref: str) -> list[str]:
    """What is wrong with a generated mirror, as far as its files show. What HACS checks
    of the repository itself (its description, topics, issues and brand) only GitHub can."""
    found = []
    manifest = json.loads(
        (out / "custom_components" / domain / "manifest.json").read_text("utf-8")
    )
    found += [
        f"manifest.json has no {key}" for key in MANIFEST_KEYS if key not in manifest
    ]
    if manifest.get("domain") != domain:
        found.append(f"manifest.json's domain is {manifest.get('domain')}")

    # Every link leaves the mirror for a real address; one into Casa Mia names a file
    # that is there at this ref.
    inside = re.compile(
        rf"https://(?:github\.com/{repo}/blob|raw\.githubusercontent\.com/{repo})/[^/]+/([^#]+)"
    )
    for _, target in LINK.findall((out / "README.md").read_text("utf-8")):
        if not target.startswith("https://"):
            found.append(f"README.md links to {target}, which works only in Casa Mia")
        elif (path := inside.match(target)) and not git(
            "ls-tree", "--name-only", ref, "--", path[1], check=False
        ):
            found.append(f"README.md links to {path[1]}, which isn't in Casa Mia")
    return found


def hassfest(out: Path) -> list[str]:
    """Home Assistant's own check of the component, when docker is here to run it. The
    mirror's workflow runs it again before anything is tagged."""
    unchecked = "hassfest not run here: {}. The mirror's workflow runs it."
    if (
        not shutil.which("docker")
        or subprocess.run(["docker", "info"], capture_output=True).returncode
    ):
        warn(unchecked.format("docker isn't running"))
        return []

    # Its image is built for amd64 only; docker emulates that elsewhere.
    say("  hassfest, in docker:")
    mount = f"{out.resolve()}:/github/workspace:ro"
    done = subprocess.run(
        ["docker", "run", "--rm", "--platform", "linux/amd64", "-v", mount, HASSFEST]
    )
    if done.returncode == 125:  # docker's own failure: no verdict on the component
        warn(unchecked.format("docker could not start it (see above)"))
        return []
    if done.returncode:
        return ["hassfest failed (its output is above)"]
    good("hassfest passed")
    return []


def follow(repo: str, what: str, *narrow: str, **match: str) -> None:
    """Follows a workflow run on GitHub to its end; Stop unless it succeeded. A run just
    started can take a moment to be listed, so it is looked for over two minutes."""
    deadline = time.monotonic() + 120
    while True:
        runs = json.loads(
            run(
                "gh", "run", "list", "--repo", repo, "--limit", "30", *narrow,
                "--json", "databaseId,headBranch,url",
            )
        )  # fmt: skip
        runs = [r for r in runs if all(r[key] == value for key, value in match.items())]
        if runs:
            break
        if time.monotonic() > deadline:
            raise Stop(f"{what} has no run on {repo}: it must succeed first.")
        say(f"  waiting for {what} to start …")
        time.sleep(10)

    url, number = runs[0]["url"], str(runs[0]["databaseId"])
    say(f"  {what}: {url}")
    watch = ["gh", "run", "watch", number, "--repo", repo]
    if subprocess.run([*watch, "--exit-status", "--interval", "15"]).returncode:
        # The watch also fails when its connection drops (2026.11.3's first mirror run
        # was reported failed while it passed): GitHub's own answer decides.
        state = run(
            "gh", "run", "view", number, "--repo", repo,
            "--json", "status,conclusion", "--jq", '.status + " " + .conclusion',
            check=False,
        )  # fmt: skip
        if state != "completed success":
            if not state.startswith("completed"):
                raise Stop(f"Lost track of {what} before it ended: {url}")
            raise Stop(f"{what} did not succeed: {url}")
    good(f"{what} succeeded")


def publish(domain: str, repo: str, owner: str, version: str) -> str:
    """Brings one mirror to `version`, from Casa Mia's tag of that name. Returns what was
    done, in a word or two; Stop says why it wasn't."""
    mirror = f"{owner}/{PUBLISHED[domain]}"
    with (
        tempfile.TemporaryDirectory() as folder,
        tempfile.TemporaryDirectory() as spare,
    ):
        work = Path(folder)
        manifest = build(domain, repo, version, owner, work)
        # Outside the mirror's tree: a release asset, never a committed file.
        archive = package(
            work / "custom_components" / domain, Path(spare) / zip_name(domain)
        )
        wrong = (
            problems(work, domain, repo, version)
            + archive_problems(archive, domain, version)
            + hassfest(work)
        )
        if wrong:
            raise Stop("\n    ".join(wrong))

        # The repository, with what HACS's validation wants it to say about itself.
        if not run("gh", "repo", "view", mirror, "--json", "name", check=False):
            run("gh", "repo", "create", mirror, "--public")
            good(f"{mirror} created")
        about = " ".join(
            git("show", f"{version}:{guide_of(domain)}").split("\n\n")[1].split()
        )
        run(
            "gh", "repo", "edit", mirror, "--description", about, "--add-topic", TOPICS,
            "--enable-wiki=false", "--enable-projects=false",
        )  # fmt: skip

        # The generated tree as a commit on the mirror's history: git says whether it is
        # new, already pushed, or already this version.
        def at(*args: str, check: bool = True) -> str:
            return git("-C", folder, *args, check=check)

        at("init", "-q", "-b", "main")
        at(
            "remote",
            "add",
            "origin",
            mirror_url(git("config", "remote.origin.url"), mirror),
        )
        at("fetch", "-q", "--tags", "origin")
        at(
            "add", "-A", "--force"
        )  # everything generated, whatever the user's ignores say
        new = at("write-tree")
        tagged = at(
            "rev-parse", "-q", "--verify", f"refs/tags/{version}^{{tree}}", check=False
        )
        head = at("rev-parse", "-q", "--verify", "origin/main^{tree}", check=False)
        action = decide(new, tagged, head)
        if action == "stop":
            raise Stop(
                f"{mirror} already has a {version} holding different files. A published"
                " version is never changed: release the next version instead."
            )
        if head:
            at("reset", "-q", "--soft", "origin/main")
        commit = git("rev-parse", f"{version}^{{commit}}")
        if action == "commit":
            at(
                "commit",
                "-q",
                "-m",
                f"{manifest['name']} {version}\n\nGenerated from {repo} at {commit}.",
            )
            at("push", "-q", "origin", "HEAD:refs/heads/main")
            good(f"{mirror}: pushed")

        # Tagged only once its own validation has passed.
        if action != "done":
            follow(
                mirror, f"{mirror}'s validation", "--commit", at("rev-parse", "HEAD")
            )
            at("tag", version)
            at("push", "-q", "origin", f"refs/tags/{version}")
        attach_missing(domain, mirror, at, Path(spare))
        if not run(
            "gh",
            "release",
            "view",
            version,
            "--repo",
            mirror,
            "--json",
            "tagName",
            check=False,
        ):
            run(
                "gh", "release", "create", version, str(archive), "--repo", mirror,
                "--verify-tag",
                "--title", f"{manifest['name']} {version}",
                "--notes",
                f"Generated from [Casa Mia {version}](https://github.com/{repo}/releases/tag/{version}),"
                f" commit {commit}. What changed is in Casa Mia's release notes.",
            )  # fmt: skip
        return "already published" if action == "done" else "published"


def attach_missing(domain: str, mirror: str, at, spare: Path) -> None:
    """Gives each release of the mirror that has no ZIP one, before a release with
    `zip_release` exists to need it: a store reads hacs.json from the latest release and
    then downloads the ZIP of whichever version is chosen, so an older release without
    one would fail to install (HACS 2.0.5 `repositories/base.py`). The ZIP is built from
    Casa Mia's tag of the same name, and only when that holds the very files the
    mirror's tag does (the same git tree), so the release's files are not changed."""
    name = zip_name(domain)
    listing = run(
        "gh", "api", f"repos/{mirror}/releases?per_page=100", "--jq",
        '.[] | [.tag_name, ([.assets[].name] | join(","))] | @tsv',
    )  # fmt: skip
    for line in listing.splitlines():
        tag, _, assets = line.partition("\t")
        if name in assets.split(","):
            continue
        theirs = at(
            "rev-parse", f"refs/tags/{tag}:custom_components/{domain}", check=False
        )
        ours = git("rev-parse", f"{tag}:{COMPONENTS}/{domain}", check=False)
        if not theirs or theirs != ours:
            warn(
                f"{mirror} {tag}: not given {name}, as Casa Mia's {tag} holds other files"
            )
            continue
        archive = package(component_at(domain, tag, spare / tag), spare / tag / name)
        if wrong := archive_problems(archive, domain, tag):
            raise Stop(f"{name} for {tag}:\n    " + "\n    ".join(wrong))
        run("gh", "release", "upload", tag, str(archive), "--repo", mirror)
        good(f"{mirror} {tag}: {name} attached")


def publish_all(repo: str, version: str) -> int:
    if versioning.parse(version)[3] is not None:
        raise Stop(
            f"{version} is a build, and mirrors are published from releases."
            " --dry-run shows what one would hold."
        )
    git("fetch", "-q", "--tags", "origin")
    if not git("tag", "--list", version):
        raise Stop(f"There is no tag {version}: release it first (tools/release.py).")

    # Which mirrors this release brings, and whose they are.
    todo, outcome = {}, {}
    for domain, name in PUBLISHED.items():
        manifest = manifest_at(domain, version)
        owner = mirror_owner(
            repo, manifest["issue_tracker"], os.environ.get("CM_MIRROR_OWNER")
        )
        if manifest["version"] != version:
            say(f"  {name}: not changed in {version} (it is at {manifest['version']}).")
        elif not owner:
            say(
                f"  {name}: skipped. {repo} is a fork of the repository it belongs to;"
                " set CM_MIRROR_OWNER to publish a mirror of your own."
            )
        else:
            todo[domain] = owner
    if not todo:
        say("  No mirror to publish.")
        return 0
    names = ", ".join(f"{owner}/{PUBLISHED[domain]}" for domain, owner in todo.items())
    if ask(f"Publish {version} to {names}?", "yn") != "y":
        say(f"  Not published. Later: tools/mirror.py {version}")
        return 1

    follow(
        repo,
        "Casa Mia's Release workflow",
        "--workflow",
        "release.yml",
        headBranch=version,
    )
    for domain, owner in todo.items():
        mirror = f"{owner}/{PUBLISHED[domain]}"
        try:
            outcome[mirror] = publish(domain, repo, owner, version)
        except Stop as stop:
            outcome[mirror] = f"NOT published: {stop}"

    # Each mirror by name: never "all done" when only some were.
    say("\n  Mirrors:")
    for mirror, result in outcome.items():
        (warn if result.startswith("NOT") else good)(f"{mirror}: {result}")
    return int(any(result.startswith("NOT") for result in outcome.values()))


def dry_run(repo: str, ref: str) -> int:
    commit = git("rev-parse", f"{ref}^{{commit}}")
    app = version_at(ref)
    say(f"Dry run from {ref} ({commit[:10]}, Casa Mia {app}). Nothing is published.")
    wrong = []
    for domain, name in PUBLISHED.items():
        manifest = manifest_at(domain, ref)
        owner = mirror_owner(
            repo, manifest["issue_tracker"], os.environ.get("CM_MIRROR_OWNER")
        )
        mirror = f"{owner or repo.split('/')[0]}/{name}"
        out = Path(tempfile.mkdtemp(prefix=f"{name}-"))  # kept, to be looked at
        build(domain, repo, ref, mirror.split("/")[0], out)
        count = sum(1 for path in out.rglob("*") if path.is_file())
        say(f"\n  {mirror}: {count} files in {out}")
        archive = package(
            out / "custom_components" / domain,
            out.with_name(f"{out.name}-{zip_name(domain)}"),
        )
        say(f"  its release's ZIP: {archive} ({archive.stat().st_size // 1024} KB)")

        found = (
            problems(out, domain, repo, ref)
            + archive_problems(archive, domain, ref)
            + hassfest(out)
        )
        for problem in found:
            warn(problem)
        if not found:
            good("its files pass every check that can be run here")
        wrong += found

        say(
            f"  {manifest['name']} is at {manifest['version']}. A release publishes it when"
            "\n  that is the release's own version, as it is for a component changed in it."
        )
        if not owner:
            warn(
                f"{repo} is a fork: skipped at a release unless CM_MIRROR_OWNER is set."
            )
        say(
            "  At a release, after its Release workflow has succeeded:"
            f"\n    gh repo create {mirror} --public          (if it is missing)"
            f"\n    gh repo edit {mirror} --description … --add-topic {TOPICS}"
            "\n    git push origin main                      (the files above, one commit)"
            "\n    wait for the mirror's Validate workflow   (HACS's action and hassfest)"
            "\n    git push origin <version>; gh release create <version> <its ZIP>"
            "\n    gh release upload <tag> <its ZIP>       (each release without one)"
            "\n  Checked only on GitHub, by HACS's action: the repository's description,"
            "\n  topics and issues, and its brand."
        )
    return int(bool(wrong))


def main() -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").splitlines()[0])
    parser.add_argument(
        "ref",
        nargs="?",
        help="the release to publish (default: this checkout's version);"
        " with --dry-run, any commit (default: HEAD)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="generate and check only; publishes nothing",
    )
    args = parser.parse_args()
    try:
        repo = github_repo()
        if not repo:
            raise Stop("origin isn't on GitHub, where the mirrors go.")
        if args.dry_run:
            return dry_run(repo, args.ref or "HEAD")
        return publish_all(repo, args.ref or versioning.current())
    except Stop as stop:
        say(f"\n  ■ {stop}")
        return 1
    except KeyboardInterrupt:
        say("\n  ■ Stopped. Run it again to carry on.")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
